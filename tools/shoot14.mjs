import { createRequire } from "module"; const require = createRequire("/tmp/adflank-ui/tools/package.json"); const puppeteer = require("puppeteer-core");
const base = process.argv[2];
const b = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const p = await b.newPage(); await p.setViewport({ width: 1440, height: 900 });
const errs = []; p.on("pageerror", (e) => errs.push("PAGEERR " + e.message)); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
const W = (ms) => new Promise((r) => setTimeout(r, ms));
await p.goto(base + "/#map", { waitUntil: "networkidle2", timeout: 90000 }); await W(4000);
await p.screenshot({ path: "shots/ui-main.png" });
await p.click("#layers-btn"); await W(500); await p.screenshot({ path: "shots/ui-layers.png" });
await p.evaluate(() => document.querySelector('.cmp[data-cmp="qloo"]').click()); await W(3000);
console.log("layers label:", await p.evaluate(() => document.querySelector("#layers-label").innerText), "| pop closed:", await p.evaluate(() => document.querySelector("#layers-pop").hidden));
await p.click("#menu-btn"); await W(400); await p.screenshot({ path: "shots/ui-menu.png" });
await p.evaluate(() => document.querySelector("#races-btn").click()); await W(1200);
console.log("panel open:", await p.evaluate(() => document.querySelector("#panel").classList.contains("open")));
await p.screenshot({ path: "shots/ui-panel.png" });
await p.evaluate(() => document.querySelector("#pclose").click()); await W(600);
await p.evaluate(() => document.querySelector("#predictions").scrollIntoView()); await W(800);
await p.screenshot({ path: "shots/ui-preds.png" });
console.log("rows:", await p.evaluate(() => document.querySelectorAll("#ptable tbody tr").length), "| sub:", await p.evaluate(() => document.querySelector("#preds-sub").innerText));
console.log("errors:", JSON.stringify(errs.slice(0, 8)));
await b.close();
