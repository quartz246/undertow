import { createRequire } from "module"; const require = createRequire("/tmp/adflank-ui/tools/package.json"); const puppeteer = require("puppeteer-core");
const base = process.argv[2] || "http://127.0.0.1:8740";
const b = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const p = await b.newPage(); await p.setViewport({ width: 1440, height: 900 });
const errs = []; p.on("console", (m) => m.type() === "error" && errs.push(m.text())); p.on("pageerror", (e) => errs.push("PAGEERR " + e.message));
await p.goto(base, { waitUntil: "networkidle2", timeout: 60000 }); await new Promise((r) => setTimeout(r, 4000));
await p.screenshot({ path: "shots/1-home.png" });
await p.evaluate(() => document.querySelector('.race[data-id="OH-S2"]')?.click()); await new Promise((r) => setTimeout(r, 4000));
await p.screenshot({ path: "shots/2-ohio.png" });
await p.evaluate(() => document.querySelector('[data-mode="undertow"]').click()); await new Promise((r) => setTimeout(r, 2500));
await p.screenshot({ path: "shots/3-undertow.png" });
await p.evaluate(() => { document.querySelector('[data-mode="forecast"]').click(); __map.jumpTo({ center: [-82.99, 39.98], zoom: 8.3 }); }); await new Promise((r) => setTimeout(r, 5000));
await p.screenshot({ path: "shots/4-cells.png" });
await p.evaluate(() => { document.querySelector("#back").click(); }); await new Promise((r) => setTimeout(r, 1500));
await p.evaluate(() => document.querySelector("#how-open").click()); await new Promise((r) => setTimeout(r, 800));
await p.screenshot({ path: "shots/5-how.png" });
await p.setViewport({ width: 400, height: 860 }); await p.evaluate(() => document.querySelector("#how").close()); await new Promise((r) => setTimeout(r, 1500));
await p.screenshot({ path: "shots/6-mobile.png", fullPage: false });
console.log("errors:", JSON.stringify(errs.slice(0, 10)));
await b.close();
